// Command gbkgen 从代码页本身生成 internal/gbkx 使用的 GBK 表：Windows 以
// C_936.NLS 提供该表，其中没有任何猜测成分。
//
// 在 Windows 上运行并提交其写出的文件；该表是数据而非代码，审查生成表是确认
// 其来自真实代码页、而非某人臆想的唯一方式。
//
// 依赖 Windows API,只能在 windows 上构建运行。
//
//go:build windows

package main

import (
	"flag"
	"fmt"
	"os"

	"golang.org/x/sys/windows"
)

func main() {
	cp := flag.Int("codepage", 936, "code page to dump")
	out := flag.String("o", "", "output Go file")
	flag.Parse()

	if *out == "" {
		fmt.Fprintln(os.Stderr, "usage: gbkgen -o internal/gbkx/table.go [-codepage 936]")
		os.Exit(2)
	}

	var leads, trails []byte
	var runes []rune
	for lead := 0x81; lead <= 0xFE; lead++ {
		for trail := 0x40; trail <= 0xFE; trail++ {
			if trail == 0x7F {
				continue
			}
			b := [2]byte{byte(lead), byte(trail)}
			r, ok := decode(*cp, b[:])
			if !ok {
				continue
			}
			leads = append(leads, byte(lead))
			trails = append(trails, byte(trail))
			runes = append(runes, r)
		}
	}
	if len(leads) < 20000 {
		fmt.Fprintf(os.Stderr, "only %d pairs: the code page is not what was expected\n", len(leads))
		os.Exit(1)
	}

	w, err := os.Create(*out)
	if err != nil {
		fmt.Fprintf(os.Stderr, "create: %v\n", err)
		os.Exit(1)
	}
	defer w.Close()

	fmt.Fprintf(w, "// Code generated by tools/gbkgen from Windows code page %d. DO NOT EDIT.\n", *cp)
	fmt.Fprintf(w, "\npackage gbkx\n\n")
	fmt.Fprintf(w, "// tableSize 表示代码页定义的双字节对数量。\n")
	fmt.Fprintf(w, "const tableSize = %d\n\n", len(leads))

	writeBytes(w, "tableLead", leads)
	writeBytes(w, "tableTrail", trails)

	fmt.Fprintf(w, "// tableRune 保存每个字节对对应的 Unicode 字符。\n")
	fmt.Fprintf(w, "var tableRune = [tableSize]rune{\n")
	for i, r := range runes {
		if i%8 == 0 {
			fmt.Fprintf(w, "\t")
		}
		fmt.Fprintf(w, "0x%04X,", r)
		if i%8 == 7 {
			fmt.Fprintf(w, "\n")
		} else {
			fmt.Fprintf(w, " ")
		}
	}
	fmt.Fprintf(w, "\n}\n")

	fmt.Printf("wrote %s: %d pairs from code page %d\n", *out, len(leads), *cp)
}

// writeBytes 每个条目写入一个字节，每行十六个。
func writeBytes(w *os.File, name string, vals []byte) {
	fmt.Fprintf(w, "var %s = [tableSize]byte{\n", name)
	for i, v := range vals {
		if i%16 == 0 {
			fmt.Fprintf(w, "\t")
		}
		fmt.Fprintf(w, "0x%02X,", v)
		if i%16 == 15 {
			fmt.Fprintf(w, "\n")
		} else {
			fmt.Fprintf(w, " ")
		}
	}
	fmt.Fprintf(w, "\n}\n\n")
}

// decode 请求 Windows 转换代码页 cp 中的一个双字节对。
func decode(cp int, b []byte) (rune, bool) {
	const mbPrecomposed = 0x00000001
	var wide [4]uint16
	n, err := windows.MultiByteToWideChar(uint32(cp), mbPrecomposed,
		&b[0], int32(len(b)), &wide[0], int32(len(wide)))
	if err != nil || n != 1 || wide[0] == 0 {
		return 0, false
	}
	return rune(wide[0]), true
}
